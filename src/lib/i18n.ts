/**
 * Multi-language support for the customer-facing tracking page (and its
 * chat + support widgets) — the pages a customer opens without ever
 * signing in, so they need to work in whatever language that customer
 * reads, not just English.
 *
 * Originally English/French only (Quebec's language rules require
 * consumer-facing communication to be available in French). Extended to
 * cover the languages most commonly spoken across Canada's delivery
 * customer base. Internal staff screens (admin/merchant/driver portals)
 * stay English-first for now — add keys below and they'll pick up
 * automatically if that ever changes.
 *
 * Locale resolution order: explicit ?lang= → signed-in user's saved
 * preference → Accept-Language header → English.
 *
 * Adding another language later is just: add its code to LOCALES, add a
 * Dict below with the same keys, add its native-script label to
 * LOCALE_LABEL, and (if it reads right-to-left) add it to RTL_LOCALES.
 */

